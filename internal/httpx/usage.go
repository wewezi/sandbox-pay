// UsageRecord contains only request metadata and historical attribution.
// Credentials, request/response bodies, headers and query strings are excluded.
type UsageRecord struct {
	RequestID      string
	Method         string
	Path           string
	StatusCode     int
	DurationMS     float64
	GroupID        *int64
	GroupName      string
	APIKeyID       *int64
	APIKeyName     string
	KeyPrefix      string
	KeySuffix      string
	ClientIP       string
	ClientLocation string
	OrderNo        string
	ErrorMessage   string
	CreatedAt      time.Time
}

// UsageOptions supplies persistence and optional attribution/location lookups.
// LookupKey is metadata-only and must not authenticate or update a token.
type UsageOptions struct {
	Record      func(UsageRecord) error
	LookupKey   func(string) (*db.ActiveKeyHit, error)
	LocateIP    func(string) string
	WriteFailed func()
}

type usageTrace struct {
	mu     sync.Mutex
	record UsageRecord
	redact func(string, int) string
}

// BindUsageAPIKey snapshots attribution onto the shared trace before the guard
// clones the request context. It deliberately copies no credential material.
func BindUsageAPIKey(ctx context.Context, group *db.Group, key *db.APIKey) {
	trace, _ := ctx.Value(keyUsage).(*usageTrace)
	if trace == nil || key == nil {
		return
	}
	trace.mu.Lock()
	defer trace.mu.Unlock()
	keyID := key.ID
	groupID := key.GroupID
	trace.record.APIKeyID, trace.record.GroupID = &keyID, &groupID
	trace.record.APIKeyName = trace.redact(key.Name, 200)
	// Prefix/suffix are already bounded display metadata generated by the repo.
	// Retain them so users can distinguish tokens without exposing the token.
	trace.record.KeyPrefix = usageText(key.KeyPrefix, 32)
	trace.record.KeySuffix = usageText(key.KeySuffix, 8)
	if group != nil {
		trace.record.GroupName = trace.redact(group.Name, 200)
	}
}

var usageOrderPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{1,128}$`)
var usageSecretPattern = regexp.MustCompile(`(?i)(?:sp_sandbox_[A-Za-z0-9_-]*|whsec_[A-Za-z0-9_-]*|sha256:[a-f0-9]{64})`)

// BindUsageOrder records an explicitly selected/validated order reference. It
// does not read arbitrary JSON fields or query parameters on the caller's behalf.
func BindUsageOrder(ctx context.Context, orderNo string) {
	trace, _ := ctx.Value(keyUsage).(*usageTrace)
	if trace == nil || !usageOrderPattern.MatchString(orderNo) || trace.redact(orderNo, 128) != orderNo {
		return
	}
	trace.mu.Lock()
	defer trace.mu.Unlock()
	trace.record.OrderNo = orderNo
}

func bindUsageError(ctx context.Context, status int, message string) {
	trace, _ := ctx.Value(keyUsage).(*usageTrace)
	if trace == nil {
		return
	}
	trace.mu.Lock()
	defer trace.mu.Unlock()
	if status >= http.StatusInternalServerError {
		message = "Internal server error"
	}
	trace.record.ErrorMessage = trace.redact(message, 500)
}

func usageText(value string, limit int) string {
	value = strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, value)
	characters := []rune(strings.TrimSpace(value))
	if len(characters) > limit {
		characters = characters[:limit]
	}
	return string(characters)
}

func usageRedactor(rawKey string) func(string, int) string {
	return func(value string, limit int) string {
		if rawKey != "" {
			value = strings.ReplaceAll(value, rawKey, "[REDACTED]")
			value = strings.ReplaceAll(value, db.HashAPIKey(rawKey), "[REDACTED]")
		}
		value = usageSecretPattern.ReplaceAllString(value, "[REDACTED]")
		return usageText(value, limit)
	}
}

// CaptureAPIUsage belongs outside rate limiters and authentication guards. The
// sink runs after the handler completes, so it cannot nest a SQLite transaction.
func CaptureAPIUsage(options UsageOptions) func(http.Handler) http.Handler {
	return func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			started := time.Now()
			rawKey := bearerToken(r.Header.Get("Authorization"))
			redact := usageRedactor(rawKey)
			trace := &usageTrace{redact: redact, record: UsageRecord{
				RequestID: redact(CorrelationID(r.Context()), 128),
				Method:    redact(r.Method, 16), Path: redact(r.URL.Path, 300),
				CreatedAt: started.UTC(),
			}}
			r = r.WithContext(context.WithValue(r.Context(), keyUsage, trace))
			writer := &usageResponseWriter{ResponseWriter: w}
			defer func() {
				panicValue := recover()
				trace.mu.Lock()
				trace.record.DurationMS = float64(time.Since(started)) / float64(time.Millisecond)
				trace.record.StatusCode = writer.status
				if trace.record.StatusCode == 0 {
					trace.record.StatusCode = http.StatusOK
				}
				if panicValue != nil {
					trace.record.StatusCode = http.StatusInternalServerError
					trace.record.ErrorMessage = "Internal server error"
				}
				trace.mu.Unlock()
				finishUsage(options, r, trace, rawKey)
				if panicValue != nil {
					panic(panicValue)
				}
			}()
			next.ServeHTTP(writer, r)
		})
	}
}

// Metadata and persistence failures must never alter the caller's response.
func finishUsage(options UsageOptions, r *http.Request, trace *usageTrace, rawKey string) {
	defer func() {
		if recover() != nil {
			reportUsageWriteFailed(options)
		}
	}()
	trace.mu.Lock()
	unattributed := trace.record.APIKeyID == nil
	trace.mu.Unlock()
	if unattributed && rawKey != "" && options.LookupKey != nil {
		if hit, err := options.LookupKey(rawKey); err == nil && hit != nil {
			BindUsageAPIKey(r.Context(), hit.Group, hit.Key)
		}
	}
	// Copy the completed trace under its lock, then perform lookups and IO without
	// holding it. Any handler-owned trace updates cannot race with persistence.
	trace.mu.Lock()
	record := trace.record
	trace.mu.Unlock()
	addr, err := netip.ParseAddr(ClientIP(r))
	if err == nil && addr.Zone() == "" && !addr.IsUnspecified() && !addr.IsMulticast() {
		record.ClientIP = addr.Unmap().String()
		if options.LocateIP != nil {
			record.ClientLocation = options.LocateIP(record.ClientIP)
		}
	}
	if record.StatusCode >= http.StatusBadRequest && record.ErrorMessage == "" {
		record.ErrorMessage = http.StatusText(record.StatusCode)
	}
	if options.Record != nil {
		if err := options.Record(record); err != nil {
			reportUsageWriteFailed(options)
		}
	}
}

func reportUsageWriteFailed(options UsageOptions) {
	defer func() { _ = recover() }()
	if options.WriteFailed != nil {
		options.WriteFailed()
	}
}

type usageResponseWriter struct {
	http.ResponseWriter
	status int
}

// Unwrap lets http.ResponseController reach optional underlying capabilities.
func (w *usageResponseWriter) Unwrap() http.ResponseWriter { return w.ResponseWriter }

func (w *usageResponseWriter) FlushError() error {
	if err := http.NewResponseController(w.ResponseWriter).Flush(); err != nil {
		return err
	}
	if w.status == 0 {
		w.status = http.StatusOK
	}
	return nil
}

func (w *usageResponseWriter) WriteHeader(status int) {
	if w.status == 0 && (status >= 200 || status == http.StatusSwitchingProtocols) {
		w.status = status
	}
	w.ResponseWriter.WriteHeader(status)
}

func (w *usageResponseWriter) Write(data []byte) (int, error) {
	if w.status == 0 {
		w.status = http.StatusOK
	}
	return w.ResponseWriter.Write(data)
}
